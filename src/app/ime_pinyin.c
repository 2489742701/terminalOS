const int ime_table_count = (int)(sizeof(ime_table) / sizeof(ime_table[0]));

/* ── 二分查找 ──
   ⚠️ ime_table 是 Flash 里的 const，strcmp 走的是 cache 命中路径，
   比线性扫还便宜；但别在这里做任何动态分配（IME 在 UI 线程里跑）。 */
const char* ime_lookup(const char* py) {
  if (!py || !py[0]) return NULL;
  int lo = 0, hi = ime_table_count - 1;
  while (lo <= hi) {
    int mid = lo + (hi - lo) / 2;
    int c = strcmp(py, ime_table[mid].key);
    if (c == 0) return ime_table[mid].hanzi;
    if (c < 0) hi = mid - 1; else lo = mid + 1;
  }
  return NULL;
}

const char* ime_pick(const char* hanzi, int n, char* out4) {
  if (!hanzi || n < 0 || !out4) return NULL;
  const char* p = hanzi;
  for (int i = 0; i < n && *p; i++) {
    unsigned char c0 = (unsigned char)p[0];
    unsigned char c1 = (unsigned char)p[1];
    /* 汉字在 UTF-8 里固定 3 字节；遇到单字节说明表坏了，直接停 */
    if (c0 < 0x80) return NULL;
    int step = (c1 && (c1 & 0xC0) == 0x80) ? 3 : 1;
    p += step;
  }
  if (!*p) return NULL;
  out4[0] = p[0]; out4[1] = p[1]; out4[2] = p[2]; out4[3] = 0;
  return out4;
}

